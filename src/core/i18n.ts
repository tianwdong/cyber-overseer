export function tr(text:string,language:Language='zh',...values:(string|number)[]):string {
  let result=language==='en'?(english[text]??text):text;
  if(language==='en'&&result===text){
    const limit=/^自动恢复已达上限：(\d+)\/(\d+)。等待手动继续或提高次数上限。$/.exec(text);
    if(limit)return tr('自动恢复已达上限：{0}/{1}。等待手动继续或提高次数上限。',language,limit[1],limit[2]);
    if(text.startsWith('自动恢复等待重试：'))return english['自动恢复等待重试：']+text.slice('自动恢复等待重试：'.length);
  }
  return result.replace(/\{(\d+)\}/g,(_,n)=>String(values[Number(n)]??`{${n}}`));
}
